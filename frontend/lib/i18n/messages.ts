type Messages = typeof messages;
type DotPrefix<TPrefix extends string, TKey extends string> = TPrefix extends "" ? TKey : `${TPrefix}.${TKey}`;

type DotKeys<TObject, TPrefix extends string = ""> = {
  [TKey in keyof TObject & string]: TObject[TKey] extends string
    ? DotPrefix<TPrefix, TKey>
    : TObject[TKey] extends readonly string[]
      ? never
      : DotKeys<TObject[TKey], DotPrefix<TPrefix, TKey>>;
}[keyof TObject & string];

// Paths that resolve to a string array, consumed via `translateList` / `tList`.
type ListKeys<TObject, TPrefix extends string = ""> = {
  [TKey in keyof TObject & string]: TObject[TKey] extends readonly string[]
    ? DotPrefix<TPrefix, TKey>
    : TObject[TKey] extends string
      ? never
      : ListKeys<TObject[TKey], DotPrefix<TPrefix, TKey>>;
}[keyof TObject & string];

export type MessageKey = DotKeys<Messages[typeof defaultLocale]>;
export type MessageListKey = ListKeys<Messages[typeof defaultLocale]>;

function getByPath(locale: Locale, key: string) {
  return key.split(".").reduce<unknown>((value, segment) => {
    if (value && typeof value === "object" && segment in value) return (value as Record<string, unknown>)[segment];
    return undefined;
  }, messages[locale]);
}

export function translate(locale: Locale, key: MessageKey, values?: Record<string, string | number>) {
  const raw = getByPath(locale, key) ?? getByPath(defaultLocale, key) ?? key;
  const template = String(raw);

  if (!values) return template;

  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function translateList(locale: Locale, key: MessageListKey): string[] {
  const raw = getByPath(locale, key) ?? getByPath(defaultLocale, key);
  return Array.isArray(raw) ? raw.map(String) : [];
}

export function isLocale(value: string | null | undefined): value is Locale {
  return Boolean(value && (locales as readonly string[]).includes(value));
}
